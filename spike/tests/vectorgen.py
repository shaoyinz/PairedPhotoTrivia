"""Test vectors for the Swift port (§1.9): every public pure function on synthetic inputs, with the
outputs the spike gives. `make vectors` rewrites tests/vectors/*.json from this file, and
`test_vectors.py` fails while they are stale, e.g. after the §1.8 sweep moves a default.

One file per module: {"_": note, "constants": {NAME: value}, "cases": [{"name", "fn", "args",
"expected" or "raises"}]}.

- `fn` is `module.function`, or `module.Class.method` with `self` among the args. `pipeline` is
  the whole spike on one couple (`pipeline` below).
- `args` names every parameter, defaults included, so no case leans on the port's defaults.
  `constants` holds the module's own constants, so the port can check its values against them.
- A dataclass is an object of its fields. Two arg types are built, not read: a CommuteBuffer
  from `commute_buffer`'s parameters, a Homes from `Homes.of`'s.
- bytes (salts, hashes) are lowercase hex. A frozenset is a list sorted by each item's JSON:
  compare it as a set. In an output, a photo is its asset_id.
- `raises` names the exception class in place of an output.
- Floats are written exactly. Compare them to within 1e-9: the port may sum in another order.
"""

