# codec


def encode(v: Any, *, out: bool = False) -> Any:
    if v is None or isinstance(v, (bool, int, float, str)):
        return v
    if isinstance(v, bytes):
        return v.hex()
    if out and isinstance(v, PhotoMeta):
        return v.asset_id
    if is_dataclass(v):
        return {f.name: encode(getattr(v, f.name), out=out) for f in fields(v)}
    if isinstance(v, (set, frozenset)):
        return sorted((encode(x, out=out) for x in v), key=lambda x: json.dumps(x, sort_keys=True))
    if isinstance(v, (list, tuple, range)):
        return [encode(x, out=out) for x in v]
    if isinstance(v, dict):
        return {k: encode(x, out=out) for k, x in v.items()}
    raise TypeError(f"cannot encode {type(v).__name__}")


def decode(v: Any, tp: Any) -> Any:
    origin, targs = typing.get_origin(tp), typing.get_args(tp)
    if origin in (typing.Union, types.UnionType):
        [inner] = [t for t in targs if t is not type(None)]
        return None if v is None else decode(v, inner)
    if isinstance(tp, NewType):
        return decode(v, tp.__supertype__)
    if tp is bytes:
        return bytes.fromhex(v)
    if tp is float:
        return float(v)
    if tp in (int, str, bool):
        return v
    if tp in BUILT:
        return call(BUILT[tp], v)
    if is_dataclass(tp):
        hints = typing.get_type_hints(tp)
        return tp(**{k: decode(x, hints[k]) for k, x in v.items()})
    if origin is frozenset:
        return frozenset(decode(x, targs[0]) for x in v)
    if origin is tuple:
        return tuple(decode(x, t) for x, t in zip(v, targs, strict=True))
    if origin in (list, Sequence, Iterable):
        return [decode(x, targs[0]) for x in v]
    raise TypeError(f"cannot decode {tp}")


def qualname(fn: Callable[..., Any]) -> str:
    module = fn.__module__
    return f"{module.removeprefix('photoquiz.')}.{fn.__qualname__}" if module.startswith("photoquiz.") else fn.__name__


def resolve(name: str) -> Callable[..., Any]:
    if name == "pipeline":
        return pipeline
    module, *path = name.split(".")
    obj: Any = importlib.import_module(f"photoquiz.{module}")
    for part in path:
        obj = getattr(obj, part)
    return obj


def call(fn: Callable[..., Any], args: dict[str, Any]) -> Any:
    hints = typing.get_type_hints(fn)
    if "self" in inspect.signature(fn).parameters:
        hints["self"] = getattr(importlib.import_module(fn.__module__), fn.__qualname__.split(".")[0])
    return fn(**{k: decode(v, hints[k]) for k, v in args.items()})


def run(c: dict[str, Any]) -> dict[str, Any]:
    """A case's outcome, from its JSON alone: what the port does."""
    try:
        return {"expected": encode(call(resolve(c["fn"]), c["args"]), out=True)}
    except ValueError as e:
        return {"raises": type(e).__name__}


def bound(fn: Callable[..., Any], *args: Any, **kw: Any) -> dict[str, Any]:
    b = inspect.signature(fn).bind(*args, **kw)
    b.apply_defaults()
    return dict(b.arguments)


def case(name: str, fn: Callable[..., Any], **kw: Any) -> dict[str, Any]:
    c = {"name": name, "fn": qualname(fn), "args": encode(bound(fn, **kw))}
    return c | run(c)


def buf(home: LatLon, work: LatLon | None = None, km: float = commute.BUFFER_KM) -> dict[str, Any]:
    """A CommuteBuffer arg, as the parameters that build it."""
    return bound(commute.commute_buffer, home, work, km)


def homes(a: Anchors, b: Anchors, **kw: Any) -> dict[str, Any]:
    """A Homes arg, as the parameters that build it."""
    return bound(trips.Homes.of, a, b, **kw)


def constants(module: types.ModuleType) -> dict[str, Any]:
    """The upper-case names the module assigns itself, not the ones it imports."""
    names = []
    for node in ast.parse(inspect.getsource(module)).body:
        targets = (
            node.targets if isinstance(node, ast.Assign) else [node.target] if isinstance(node, ast.AnnAssign) else []
        )
        names += [t.id for t in targets if isinstance(t, ast.Name) and t.id.isupper()]
    return {n: encode(getattr(module, n)) for n in names}


def dumps(v: Any, depth: int = 0) -> str:
    """JSON with a short or flat container on one line (a photo, a key), anything else broken up."""
    flat = json.dumps(v)
    children = list(v.values()) if isinstance(v, dict) else v if isinstance(v, list) else []
    if (
        not children
        or len(flat) <= 100
        or (len(flat) <= 400 and not any(isinstance(c, (dict, list)) for c in children))
    ):
        return flat
    pad = "  " * (depth + 1)
    if isinstance(v, dict):
        lines = [f"{pad}{json.dumps(k)}: {dumps(x, depth + 1)}" for k, x in v.items()]
        return "{\n" + ",\n".join(lines) + "\n" + "  " * depth + "}"
    return "[\n" + ",\n".join(pad + dumps(x, depth + 1) for x in v) + "\n" + "  " * depth + "]"


