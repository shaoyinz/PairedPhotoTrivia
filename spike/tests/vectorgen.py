def off(origin: LatLon, x: float, y: float) -> LatLon:
    """The point (x east, y north) km from `origin` on its plane: the inverse of to_km."""
    return LatLon(
        origin.lat + y / project.KM_PER_DEG_LAT,
        origin.lon + x / (project.KM_PER_DEG_LON * math.cos(math.radians(origin.lat))),
    )


def covers(name: str, home: LatLon, work: LatLon | None, km: float, p: LatLon) -> dict:
    """A point at least 50 m from the buffer's edge, where shapely's polygon (at most 6 m inside the
    true circle) and the port's exact point-to-segment distance agree."""
    px, py = project.to_km(p, home)
    wx, wy = (0.0, 0.0) if work is None else project.to_km(work, home)
    t = max(0.0, min(1.0, (px * wx + py * wy) / (wx * wx + wy * wy))) if (wx or wy) else 0.0
    assert abs(math.hypot(px - t * wx, py - t * wy) - km) >= 0.05, name
    return case(name, commute.CommuteBuffer.covers, self=buf(home, work, km), p=p)


