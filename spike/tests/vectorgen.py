def pipeline(
    ps_a: Sequence[PhotoMeta],
    ps_b: Sequence[PhotoMeta],
    salt: bytes,
    *,
    window_days: int = 90,
    gap_hours: int = trips.GAP_HOURS,
    reach_hours: int = trips.REACH_HOURS,
    city_km: float = trips.CITY_KM,
    max_silence_hours: int = trips.MAX_SILENCE_HOURS,
    tail_gap_hours: int = trips.TAIL_GAP_HOURS,
    min_photos: int = trips.MIN_PHOTOS,
) -> dict[str, Any]:
    """As `make skeleton` runs it: each partner's filters, anchors over the last window_days and home
    history, then A expanded and B raw, salted, intersected, mapped back on A's side, and trips."""
    side: dict[str, dict[str, Any]] = {}
    for person, raw in (("a", ps_a), ("b", ps_b)):
        ps, dropped = filters.apply_all(list(raw))
        now = max(p.utc_epoch for p in ps)
        an = anchors.infer_anchors(ps, person=person, now_utc=now, window_days=window_days)
        side[person] = {"kept": ps, "dropped": dropped, "anchors": an, "eras": anchors.home_eras(ps, an, now_utc=now)}
    a, b = side["a"], side["b"]
    own_a = buckets.own_keys(a["kept"], expanded=True)
    m = matching.match(
        buckets.salted_set(own_a, salt), buckets.salted_set(buckets.own_keys(b["kept"], expanded=False), salt)
    )
    keys = buckets.matched_keys(own_a, m, salt)
    ws = trips.assemble(
        sorted(keys),
        a["anchors"],
        b["anchors"],
        ps_a=a["kept"],
        ps_b=b["kept"],
        gap_hours=gap_hours,
        reach_hours=reach_hours,
        city_km=city_km,
        max_silence_hours=max_silence_hours,
        tail_gap_hours=tail_gap_hours,
        min_photos=min_photos,
        eras_a=a["eras"],
        eras_b=b["eras"],
    )
    return {"a": a, "b": b, "matched": keys, "trips": ws}


def at_tahoe(located_a: int, located_b: int) -> dict[str, list[PhotoMeta]]:
    """A week of nights at home and of days at work each, then ten photos each together at Tahoe
    at noon on a Friday (hour H), the first `located_*` of them with GPS."""
    day = dt.date(2026, 7, 10)
    out = {}
    for person, located in (("a", located_a), ("b", located_b)):
        before = [local(d, 2.0) for d in days_before(day, 7)]
        before += [local(d, 12.0, WORK) for d in weekdays_before(day - dt.timedelta(days=1), 5)]
        out[f"ps_{person}"] = [replace(p, asset_id=f"{person}-{p.asset_id}") for p in before] + [
            photo(f"{person}-tahoe-{i}", H * 3600 + 60 * i, TAHOE if i < located else None) for i in range(10)
        ]
    return out


