def photo(asset_id: str, utc: int | None, at: LatLon | None = TAHOE, *, tz: int | None = PDT, **kw: Any) -> PhotoMeta:
    """No camera make or model, as in every iOS export (§1.2a)."""
    lat, lon = (None, None) if at is None else (at.lat, at.lon)
    return replace(PhotoMeta(asset_id, utc, tz, lat, lon, False, None, False, None, None, 4032, 3024), **kw)


def local(day: dt.date, hour: float, at: LatLon | None = HOME, tz: int = PDT, plus: int = 0) -> PhotoMeta:
    """A photo at wall-clock `hour` on local `day`, `plus` seconds later."""
    midnight = int(dt.datetime(day.year, day.month, day.day, tzinfo=dt.UTC).timestamp())
    utc = midnight + round(hour * 3600) - tz + plus
    return photo(f"p{utc}", utc, at, tz=tz)


def utc_at(day: dt.date, hour: float, tz: int) -> PhotoMeta:
    """A photo at `hour` UTC on `day`, taken where the offset is `tz`."""
    return replace(local(day, hour, tz=0), tz_offset_s=tz)


def days_before(day: dt.date, n: int) -> list[dt.date]:
    return [day - dt.timedelta(days=i) for i in range(n)]


def weekdays_before(day: dt.date, n: int) -> list[dt.date]:
    return [d for d in days_before(day, 2 * n) if d.weekday() < 5][:n]


def nights(spot: LatLon, first: dt.date, last: dt.date, every: int = 2, tz: int = PDT) -> list[PhotoMeta]:
    """A photo at 02:00 local every `every` days from first to last."""
    return [local(first + dt.timedelta(days=d), 2.0, spot, tz) for d in range(0, (last - first).days + 1, every)]


def cell(p: LatLon, precision: int = 6) -> str:
    return pgh.encode(p.lat, p.lon, precision=precision)


def centre(gh: str) -> LatLon:
    c = pgh.decode(gh)
    return LatLon(c.latitude, c.longitude)


def right(gh: str, n: int = 1) -> str:
    for _ in range(n):
        gh = pgh.get_adjacent(gh, "right")
    return gh


def key(p: LatLon, hour: int) -> BucketKey:
    return BucketKey(cell(p), hour)


def shots(person: str, n: int, hour: int = H) -> list[PhotoMeta]:
    return [photo(f"{person}-{i}", hour * 3600 + 600 + i) for i in range(n)]


def hours(person: str, *hs: int, where: LatLon | None = TAHOE) -> list[PhotoMeta]:
    """A photo at the start of each hour H + h."""
    return [photo(f"{person}-{h}", (H + h) * 3600, where) for h in hs]


def anchored(person: str, home: LatLon, work: LatLon | None = None, shared_home: bool | None = None) -> Anchors:
    return Anchors(person, home, work, cell(home, 7), None if work is None else cell(work, 7), 90, 10, 0, shared_home)


